#!/bin/sh
# Compiles src/gfx/shaders/*.vert|frag to SPIR-V (Vulkan, and D3D via Vulkan on Windows) and MSL
# (Metal) and writes them as C arrays into src/gfx/shaders/scene_shaders.h. The result is committed,
# so normal builds need none of this; rerun after editing a shader. Needs glslangValidator and
# spirv-cross (brew install glslang spirv-cross).
set -e
cd "$(dirname "$0")/../src/gfx/shaders"
out=scene_shaders.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "/* Generated by scripts/build_shaders.sh from scene.vert and scene.frag; do not edit. */"
    echo "#pragma once"
} > "$out"
for s in scene.vert scene.frag; do
    stage=${s##*.}
    glslangValidator -V "$s" -o "$tmp/$s.spv" >/dev/null
    spirv-cross "$tmp/$s.spv" --msl --msl-version 20000 --output "$tmp/$s.msl"
    id=$(echo "$s" | tr . _)
    xxd -i < "$tmp/$s.spv" | { echo "static const unsigned char ${id}_spv[] = {"; cat; echo "};"; } >> "$out"
    { cat "$tmp/$s.msl"; printf '\0'; } | xxd -i | { echo "static const unsigned char ${id}_msl[] = {"; cat; echo "};"; } >> "$out"
done
echo "wrote src/gfx/shaders/$out"
